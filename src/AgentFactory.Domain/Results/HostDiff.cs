namespace AgentFactory.Domain.Results;

/// <summary>
/// One round's change, as the <em>host</em> generated it: <c>git diff</c> run on the tree
/// the round left behind, after the container that made it was gone.
/// </summary>
/// <remarks>
/// <para>
/// This is the diff a reviewer judges, and it is deliberately not the diff the container
/// recorded. Two reasons, and the second is the important one. The container's copy is
/// bounded by the image, so on a large change it is a prefix of the change and the board
/// would be showing a reviewer part of a diff that looked like all of it. And a round
/// whose result file is missing, truncated or unreadable has <em>no</em> container copy at
/// all — and that is precisely the round a reviewer most wants to see what it managed to
/// do before it broke. The tree is on the host either way, because the host has to be
/// able to reach the round's commit once the container is gone.
/// </para>
/// <para>
/// It is generated by git, on the host, from a directory the factory itself created. There
/// is no network in it and no API behind it, which is the point: the reviewer can judge a
/// change when GitHub is unreachable, and a diff fetched from the same service that
/// produced the change would be a second opinion from the thing under review rather than
/// evidence about it.
/// </para>
/// <para>
/// It is a record and nothing else. The component that generates it — the reader that
/// runs <c>git</c> against a directory on this host — is an adapter and lives on the far
/// side of the boundary (<c>AgentFactory.Infrastructure</c>); what a reviewer is shown,
/// and what a round's result carries, is this.
/// </para>
/// </remarks>
/// <param name="Text">
/// The diff, as git wrote it. Empty when the round changed nothing, which is a real
/// outcome and not the same thing as a diff that could not be generated.
/// </param>
/// <param name="Base">The commit the diff is against — where the round began.</param>
/// <param name="Tree">
/// The lifted tree it was generated from, so a reviewer who wants the whole of it — or a
/// part the board did not render — knows exactly where to look.
/// </param>
/// <param name="ContainerBounded">
/// Whether the container's own copy of this diff was bounded by the image. Recorded
/// because it is the reason there are two observations of the same change and only one of
/// them is on the card, and a reviewer who noticed the difference is owed the answer.
/// </param>
/// <param name="UnavailableBecause">
/// Why there is no diff at all, or null when there is one — including an empty one. A
/// round that changed nothing and a round whose tree could not be read are very different
/// claims and the board says which is which.
/// </param>
public sealed record HostDiff(
    string Text,
    string Base,
    string Tree,
    bool ContainerBounded,
    string? UnavailableBecause)
{
    /// <summary>A diff that could not be generated, and why.</summary>
    public static HostDiff Unavailable(string tree, string because, bool containerBounded = false) =>
        new(string.Empty, string.Empty, tree, containerBounded, because);

    /// <summary>
    /// Whether the round's change is on the card. False for both "it changed nothing" and
    /// "there was no tree to look at", which is why the board reads
    /// <see cref="UnavailableBecause"/> rather than this.
    /// </summary>
    public bool HasText => Text.Trim().Length > 0;
}