namespace AgentFactory.Results;

using System.Diagnostics;
using System.Text;

/// <summary>
/// One round's change, as the <em>host</em> generated it: <c>git diff</c> run on the tree
/// the round left behind, after the container that made it was gone.
/// </summary>
/// <remarks>
/// <para>
/// This is the diff a reviewer judges, and it is deliberately not the diff the container
/// recorded. Two reasons, and the second is the important one. The container's copy is
/// bounded by the image, so on a large change it is a prefix of the change and the board
/// would be showing a reviewer part of a diff that looked like all of it. And a round
/// whose result file is missing, truncated or unreadable has <em>no</em> container copy at
/// all — and that is precisely the round a reviewer most wants to see what it managed to
/// do before it broke. The tree is on the host either way, because the host has to be
/// able to reach the round's commit once the container is gone (ADR-0006).
/// </para>
/// <para>
/// It is generated by git, on the host, from a directory the factory itself created. There
/// is no network in it and no API behind it, which is the point: the reviewer can judge a
/// change when GitHub is unreachable, and a diff fetched from the same service that
/// produced the change would be a second opinion from the thing under review rather than
/// evidence about it.
/// </para>
/// </remarks>
/// <param name="Text">
/// The diff, as git wrote it. Empty when the round changed nothing, which is a real
/// outcome and not the same thing as a diff that could not be generated.
/// </param>
/// <param name="Base">The commit the diff is against — where the round began.</param>
/// <param name="Tree">
/// The lifted tree it was generated from, so a reviewer who wants the whole of it — or a
/// part the board did not render — knows exactly where to look.
/// </param>
/// <param name="ContainerBounded">
/// Whether the container's own copy of this diff was bounded by the image. Recorded
/// because it is the reason there are two observations of the same change and only one of
/// them is on the card, and a reviewer who noticed the difference is owed the answer.
/// </param>
/// <param name="UnavailableBecause">
/// Why there is no diff at all, or null when there is one — including an empty one. A
/// round that changed nothing and a round whose tree could not be read are very different
/// claims and the board says which is which.
/// </param>
public sealed record HostDiff(
    string Text,
    string Base,
    string Tree,
    bool ContainerBounded,
    string? UnavailableBecause)
{
    /// <summary>A diff that could not be generated, and why.</summary>
    public static HostDiff Unavailable(string tree, string because, bool containerBounded = false) =>
        new(string.Empty, string.Empty, tree, containerBounded, because);

    /// <summary>
    /// Whether the round's change is on the card. False for both "it changed nothing" and
    /// "there was no tree to look at", which is why the board reads
    /// <see cref="UnavailableBecause"/> rather than this.
    /// </summary>
    public bool HasText => Text.Trim().Length > 0;
}

/// <summary>
/// Generates a round's diff from the tree that round left, by running git against it.
/// </summary>
/// <remarks>
/// <para>
/// The git binary is a process and the arguments go in one at a time, never through a
/// shell, on the same reasoning as the Docker CLI: a repository name, a branch and a
/// commit id are all things a project controls, and none of them may become shell syntax
/// on the way in.
/// </para>
/// <para>
/// Two settings are passed to git that the tree cannot be trusted to have set, and both
/// are refusals rather than conveniences. <c>--no-ext-diff</c> and <c>--no-textconv</c>
/// stop git running a program named in the tree's own configuration to produce the diff —
/// a <c>.gitattributes</c> line or a <c>diff = </c> driver in a repository the factory
/// did not write is an arbitrary executable, and a reviewer asking what changed must not
/// run it. <c>safe.directory</c> is passed through the environment exactly as the worker
/// image passes it: the tree was created by uid 1000 inside a Linux container, and on a
/// Linux host git refuses to read a repository it does not own, which would leave the
/// diff silently absent rather than wrong.
/// </para>
/// <para>
/// Nothing here writes to the tree. A tree lifted out of a Linux container arrives on
/// Windows with read-only pack files, and a diff is a read of them; anything that
/// deleted or moved files in there would have to clear the attributes first, and the
/// host-diff path deliberately never does.
/// </para>
/// </remarks>
public static class HostDiffReader
{
    /// <summary>The executable, resolved through <c>PATH</c>.</summary>
    public const string Executable = "git";

    /// <summary>
    /// How many lines of context git puts around a change. Written out rather than left to
    /// the tree's configuration: three is git's own default, and a diff a reviewer reads
    /// on the board should be the one <c>git diff</c> would give them.
    /// </summary>
    public const int ContextLines = 3;

    /// <summary>
    /// The git configuration a round's diff is read with: the same safe.directory the
    /// worker image sets system-wide, for the same reason and with the same scope.
    /// </summary>
    /// <remarks>
    /// A tree created by uid 1000 inside a container is a repository git refuses to read
    /// on a Linux host. Left unsaid, the round's diff would be <em>absent</em> — which
    /// reads as a round that changed nothing, the worst available answer, rather than as a
    /// visible fault. Injected through the environment rather than written into the tree,
    /// so that reading a round's diff never modifies a round's tree.
    /// </remarks>
    public static IReadOnlyDictionary<string, string> GitEnvironment { get; } = new Dictionary<string, string>(StringComparer.Ordinal)
    {
        ["GIT_CONFIG_COUNT"] = "1",
        ["GIT_CONFIG_KEY_0"] = "safe.directory",
        ["GIT_CONFIG_VALUE_0"] = "*",
    };

    /// <summary>
    /// Every argument handed to git except the ref it is diffed against. Public because the
    /// refusals in it are the point of the component rather than an implementation detail
    /// of it, and a test that could not read them could not check them.
    /// </summary>
    /// <remarks>
    /// <c>--no-ext-diff</c> and <c>--no-textconv</c> are the load-bearing pair: without
    /// them git will run a program named by the tree's own configuration to produce the
    /// diff, and the tree is a repository this factory did not write. A reviewer asking
    /// what changed must not run whatever that repository says to run.
    ///
    /// <c>core.quotepath=false</c> is a display setting — git escapes a path above ASCII
    /// by default, which would give a reviewer two spellings of the same file, one on the
    /// index line and one in git's own text underneath it.
    /// </remarks>
    public static IReadOnlyList<string> Arguments(string against) =>
    [
        "-c",
        "core.quotepath=false",
        "--no-pager",
        "diff",
        "--no-color",
        "--no-ext-diff",
        "--no-textconv",
        "--find-renames",
        $"--unified={ContextLines}",
        against,
    ];

    /// <summary>
    /// The round's diff, generated on the host from the tree the round left.
    /// </summary>
    /// <param name="tree">Where <c>docker cp</c> put the round's working tree, or null.</param>
    /// <param name="startHead">
    /// The commit the round started from, as the round's own result file recorded it, or
    /// null. Preferred, because it is the container's own observation of where it began.
    /// </param>
    /// <param name="baseBranch">
    /// The work item's base. Used only when the result file named no start commit, which
    /// is the case of a round whose result could not be read at all — and a round that
    /// broke is the one whose change a reviewer most wants to see.
    /// </param>
    /// <param name="containerBounded">
    /// Whether the container bounded its own copy of this diff, carried so the board can
    /// say why the text on the card is not the text the container recorded.
    /// </param>
    /// <param name="cancellationToken">The round's own token.</param>
    public static async Task<HostDiff> OfAsync(
        string? tree,
        string? startHead,
        string? baseBranch,
        bool containerBounded,
        CancellationToken cancellationToken)
    {
        if (string.IsNullOrWhiteSpace(tree) || !Directory.Exists(Path.Combine(tree, ".git")))
        {
            return HostDiff.Unavailable(
                tree ?? string.Empty,
                "the round's tree did not come out of its container, so there is nothing on the host to diff");
        }

        // The bases to try, in order of how well we know them. The start commit is the
        // container's own record; the branch the round was given is the next best thing
        // and is right for a fresh clone, because a fresh clone's history contains the
        // base as an ancestor whatever the round did on top of it.
        var bases = new List<string>();
        if (startHead is { Length: > 0 } start)
        {
            bases.Add(start);
        }

        if (baseBranch is { Length: > 0 } branch)
        {
            bases.Add($"refs/remotes/origin/{branch}");
        }

        if (bases.Count == 0)
        {
            return HostDiff.Unavailable(
                tree,
                "the host does not know which commit this round started from, so there is nothing to diff it against",
                containerBounded);
        }

        var failures = new List<string>();

        foreach (var base_ in bases)
        {
            var answer = await GitAsync(tree, base_, cancellationToken).ConfigureAwait(false);

            if (answer.ExitCode == 0)
            {
                return new HostDiff(answer.Output, Shorten(base_), tree, containerBounded, null);
            }

            failures.Add($"{base_}: {answer.Error}");
        }

        return HostDiff.Unavailable(
            tree,
            "git could not diff the round's tree against " + string.Join("; ", failures),
            containerBounded);
    }

    /// <summary>
    /// One <c>git diff</c>, and whatever it said. Never throws for a git that could not be
    /// started: a round whose change cannot be diffed is a round a reviewer is shown the
    /// reason for, not a round that takes the factory down with it.
    /// </summary>
    private static async Task<(int ExitCode, string Output, string Error)> GitAsync(
        string tree,
        string against,
        CancellationToken cancellationToken)
    {
        var start = new ProcessStartInfo
        {
            FileName = Executable,
            WorkingDirectory = tree,
            RedirectStandardOutput = true,
            RedirectStandardError = true,
            RedirectStandardInput = true,
            UseShellExecute = false,
            CreateNoWindow = true,
        };

        foreach (var argument in Arguments(against))
        {
            start.ArgumentList.Add(argument);
        }

        // The same safe.directory the worker image sets system-wide, for the same reason
        // and with the same scope.
        foreach (var (name, value) in GitEnvironment)
        {
            start.Environment[name] = value;
        }

        using var process = new Process { StartInfo = start };

        try
        {
            if (!process.Start())
            {
                return (ExitCode: -1, Output: string.Empty, Error: $"could not start '{Executable}'");
            }
        }
        catch (Exception failed) when (failed is not OperationCanceledException)
        {
            return (ExitCode: -1, Output: string.Empty, Error: $"there is no git on this machine's PATH: {failed.Message}");
        }

        try
        {
            process.StandardInput.Close();
        }
        catch (System.IO.IOException)
        {
            // git exited before its stdin was closed. It is not reading any more, which is
            // all closing it was for.
        }

        var output = new StringBuilder();
        var error = new StringBuilder();

        try
        {
            var stdout = process.StandardOutput.ReadToEndAsync(cancellationToken);
            var stderr = process.StandardError.ReadToEndAsync(cancellationToken);
            await process.WaitForExitAsync(cancellationToken).ConfigureAwait(false);

            output.Append(await stdout.ConfigureAwait(false));
            error.Append(await stderr.ConfigureAwait(false));

            return (process.ExitCode, GitDiff.Normalise(output.ToString()), error.ToString().Trim());
        }
        catch (OperationCanceledException)
        {
            // The round's token fired. The local git process is killed and reaped rather
            // than left running against a tree nobody is reading any more.
            try
            {
                if (!process.HasExited)
                {
                    process.Kill(entireProcessTree: true);
                }

                await process.WaitForExitAsync(CancellationToken.None).ConfigureAwait(false);
            }
            catch (Exception reaping) when (reaping is InvalidOperationException or System.IO.IOException)
            {
                // It exited between the check and the kill, which is the outcome wanted.
            }

            throw;
        }
    }

    private static string Shorten(string commit) =>
        commit.StartsWith("refs/remotes/origin/", StringComparison.Ordinal)
            ? "the base the round was given (" + commit["refs/remotes/origin/".Length..] + ")"
            : commit.Length > 7
                ? commit[..7]
                : commit;
}
